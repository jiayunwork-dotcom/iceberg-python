# The pure-Python Avro fallback is a supported configuration; it warns only
# because this environment was built without the Cython extension.
pytestmark = pytest.mark.filterwarnings("ignore:Falling back to pure Python Avro decoder")

AMOUNT = DecimalType(6, 2)
SCHEMA = Schema(
    NestedField(1, "amount", AMOUNT, required=False),
    NestedField(2, "id", LongType(), required=False),
)

SPELLINGS_100 = ["100.00", "1E+2", "100", "100.000"]

# One file per partition value.  ``rows`` are (amount, id) pairs.
ROWS_BY_FILE = {
    "a": [(Decimal("100.00"), 1), (Decimal("100.00"), 2)],
    "b": [(Decimal("99.99"), 3)],
    "f": [(Decimal("99.91"), 4)],
    # The null row shares a file with a non-null value; an all-null decimal
    # column is not representable in this writer's Parquet statistics.
    "e": [(Decimal("0.05"), 5)],
    "c": [(None, 6)],
    "d": [(Decimal("100.10"), 7)],
}

# Partition values per spec, written out by hand.
# truncate[10] over decimal(6, 2): 100.00 -> 100.00, 99.99 -> 99.90, etc.
TRUNCATE_PARTITIONS = {
    "a": Decimal("100.00"),
    "b": Decimal("99.90"),
    "f": Decimal("99.90"),
    "e": Decimal("0.00"),
    "c": None,
    "d": Decimal("100.10"),
}
IDENTITY_PARTITIONS = {
    "a": Decimal("100.00"),
    "b": Decimal("99.99"),
    "f": Decimal("99.91"),
    "e": Decimal("0.05"),
    "c": None,
    "d": Decimal("100.10"),
}
# bucket[8] partition values, computed once by hand:
# bucket(100.00)=0, bucket(99.99)=7, bucket(99.91)=4, bucket(0.05)=5, bucket(100.10)=3
BUCKET_PARTITIONS = {"a": 0, "b": 7, "f": 4, "e": 5, "c": None, "d": 3}


def _write_file(tmp, name, rows):
    path = os.path.join(tmp, f"{name}.parquet")
    table = pa.table(
        {
            "amount": pa.array([amount for amount, _ in rows], type=pa.decimal128(6, 2)),
            "id": pa.array([id for _, id in rows], type=pa.int64()),
        }
    )
    pq.write_table(table, path, store_decimal_as_integer=True)
    return path


def _build_table(tmp, spec, partitions, file_rows=None):
    catalog = InMemoryCatalog("decimal_e2e", warehouse=tmp)
    catalog.create_namespace("default")
    table = catalog.create_table(
        "default.t",
        schema=SCHEMA,
        partition_spec=spec,
        properties={TableProperties.DEFAULT_NAME_MAPPING: create_mapping_from_schema(SCHEMA).model_dump_json()},
    )
    data_files = []
    for name, rows in (file_rows or ROWS_BY_FILE).items():
        path = _write_file(tmp, name, rows)
        if all(amount is None for amount, _ in rows):
            # An all-null decimal column has no min/max statistics. Build the
            # file metadata by hand: value counts are present, bounds are
            # absent, which is exactly the "statistics missing" case that
            # must fall back to a conservative read.
            statistics = {
                "record_count": len(rows),
                "column_sizes": {},
                "value_counts": {1: len(rows)},
                "null_value_counts": {1: len(rows), 2: 0},
                "nan_value_counts": {},
                "lower_bounds": {},
                "upper_bounds": {},
                "split_offsets": [],
            }
        else:
            statistics = data_file_statistics_from_parquet_metadata(
                parquet_metadata=pq.read_metadata(path),
                stats_columns=compute_statistics_plan(table.schema(), table.metadata.properties),
                parquet_column_mapping=parquet_path_to_id_mapping(table.schema()),
            ).to_serialized_dict()
        partition = partitions[name]
        if not isinstance(partition, dict):
            partition = {spec.fields[0].name: partition}
        data_files.append(
            DataFile(
                content=DataFileContent.DATA,
                file_path=path,
                file_format=FileFormat.PARQUET,
                partition=Record(**partition),
                file_size_in_bytes=os.path.getsize(path),
                sort_order_id=None,
                spec_id=table.metadata.default_spec_id,
                equality_ids=None,
                key_metadata=None,
                **statistics,
            )
        )
    with table.transaction() as transaction:
        with transaction.update_snapshot().overwrite() as update:
            for data_file in data_files:
                update.append_data_file(data_file)
    return table


