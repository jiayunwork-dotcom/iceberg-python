"""End-to-end decimal(6, 2) query tests over truncate, identity and bucket.

The table is built by hand: the Parquet files, their Parquet statistics, the
DataFile records and the manifest are produced in this module. The expected
rows, duplicate multiplicities, file eligibility and counts are written down
explicitly; they are not generated by the binding or projection code under
test.
"""

