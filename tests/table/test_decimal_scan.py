def test_negative_and_zero_values(negative_table):
    table = negative_table
    # truncate[10] at scale 2 truncates 10 unscaled units: -10.01 -> -10.10,
    # while -10.00 and -9.99 both stay in -10.00.
    for spelling in ("-10.00", "-1E+1", "-10", "-10.000", "-10.0"):
        # n3's truncate partition is also -10.00, but its file only contains
        # -9.99, which the column statistics prune for equality.
        _assert_scan(
            table.scan(row_filter=EqualTo("amount", Decimal(spelling))),
            [10],
            ["n1"],
            1,
        )
        _assert_scan(
            table.scan(row_filter=LessThan("amount", Decimal(spelling))),
            [11],
            ["n2"],
            1,
        )
        _assert_scan(
            table.scan(row_filter=GreaterThanOrEqual("amount", Decimal(spelling))),
            [10, 12, 13, 14],
            ["n1", "n3", "z", "nz"],
            4,
        )
    for zero in ("0.00", "0", "-0", "0E+5", "-0.00"):
        _assert_scan(
            table.scan(row_filter=EqualTo("amount", Decimal(zero))),
            [13, 14],
            ["z", "nz"],
            2,
        )
        _assert_scan(
            table.scan(row_filter=LessThan("amount", Decimal(zero))),
            [10, 11, 12],
            ["n1", "n2", "n3"],
            3,
        )


def test_renamed_column_keeps_filter_meaning(truncate_table):
    table = truncate_table
    with table.update_schema() as update:
        update.rename_column("id", "identifier")
    scan = table.scan(row_filter=EqualTo("amount", Decimal("1E+2")), selected_fields=("identifier",))
    assert sorted(scan.to_arrow().column("identifier").to_pylist()) == [1, 2]
    renamed_scan = table.scan(row_filter=EqualTo("amount", Decimal("100.000")), selected_fields=("identifier",))
    assert sorted(renamed_scan.to_arrow().column("identifier").to_pylist()) == [1, 2]
    assert renamed_scan.count() == 2


def test_time_travel_to_previous_snapshot(truncate_table):
    table = truncate_table
    first_snapshot = table.metadata.current_snapshot().snapshot_id
    # Appending a file creates a new snapshot; the old snapshot's files must
    # still be filtered with the same decimal semantics.
    extra_path = _write_file(os.path.dirname(table.metadata.location.replace("file:", "")), "g", [(Decimal("100.00"), 8)])
    from pyiceberg.io.pyarrow import (
        compute_statistics_plan,
        data_file_statistics_from_parquet_metadata,
        parquet_path_to_id_mapping,
    )

    statistics = data_file_statistics_from_parquet_metadata(
        parquet_metadata=pq.read_metadata(extra_path),
        stats_columns=compute_statistics_plan(table.schema(), table.metadata.properties),
        parquet_column_mapping=parquet_path_to_id_mapping(table.schema()),
    )
    extra = DataFile(
        content=DataFileContent.DATA,
        file_path=extra_path,
        file_format=FileFormat.PARQUET,
        partition=Record(amount_trunc=Decimal("100.00")),
        file_size_in_bytes=os.path.getsize(extra_path),
        sort_order_id=None,
        spec_id=table.metadata.default_spec_id,
        equality_ids=None,
        key_metadata=None,
        **statistics.to_serialized_dict(),
    )
    with table.transaction() as transaction:
        with transaction.update_snapshot().overwrite() as update:
            update.append_data_file(extra)
    assert table.metadata.current_snapshot().snapshot_id != first_snapshot
    _assert_scan(table.scan(row_filter=EqualTo("amount", Decimal("1E+2"))), [1, 2, 8], ["a", "g"], 3)
    _assert_scan(
        table.scan(row_filter=EqualTo("amount", Decimal("1E+2")), snapshot_id=first_snapshot),
        [1, 2],
        ["a"],
        2,
    )


def test_partition_evolution_keeps_old_files(truncate_table):
    table = truncate_table
    with table.update_spec() as update:
        update.add_field("amount", BucketTransform(4), "amount_bucket")
    # The old files still use spec 0 (truncate only), new files would use both
    # fields.  Every spelling of 100.00 must find the old files.
    for spelling in SPELLINGS_100:
        _assert_scan(
            table.scan(row_filter=EqualTo("amount", Decimal(spelling))),
            [1, 2],
            ["a"],
            2,
        )
        _assert_scan(
            table.scan(row_filter=LessThan("amount", Decimal(spelling))),
            [3, 4, 5],
            ["b", "e", "f"],
            3,
        )


def test_multiple_transforms_on_same_column():
    with tempfile.TemporaryDirectory() as tmp:
        spec = PartitionSpec(
            PartitionField(1, 1000, TruncateTransform(10), "amount_trunc"),
            PartitionField(1, 1001, BucketTransform(8), "amount_bucket"),
        )
        # Both transform values are written by hand.  bucket(100.00)=0,
        # bucket(99.99)=7, bucket(99.91)=4, bucket(0.05)=5, bucket(100.10)=3.
        partitions = {
            name: {"amount_trunc": TRUNCATE_PARTITIONS[name], "amount_bucket": BUCKET_PARTITIONS[name]} for name in ROWS_BY_FILE
        }
        table = _build_table(tmp, spec, partitions)
        for spelling in SPELLINGS_100:
            # The inclusive projection is the conjunction of both transforms;
            # no partition other than truncate=100.00 AND bucket=0 survives.
            _assert_scan(table.scan(row_filter=EqualTo("amount", Decimal(spelling))), [1, 2], ["a"], 2)
            # NotEqual cannot use either transform, so every partition remains.
            _assert_scan(
                table.scan(row_filter=NotEqualTo("amount", Decimal(spelling))),
                [3, 4, 5, 7],
                ["a", "b", "c", "d", "e", "f"],
                5,
            )


def test_neighbouring_partition_is_pruned_by_second_transform():
    with tempfile.TemporaryDirectory() as tmp:
        spec = PartitionSpec(
            PartitionField(1, 1000, TruncateTransform(10), "amount_trunc"),
            PartitionField(1, 1001, BucketTransform(8), "amount_bucket"),
        )
        partitions = {
            name: {"amount_trunc": TRUNCATE_PARTITIONS[name], "amount_bucket": BUCKET_PARTITIONS[name]} for name in ROWS_BY_FILE
        }
        table = _build_table(tmp, spec, partitions)
        # A neighbouring file for 99.95 has truncate=99.90 and bucket(99.95).
        # A 100.00 query must still plan only the truncate=100.00 bucket=0
        # file; the second transform is an additional, not alternative, filter.
        import mmh3

        from pyiceberg.utils.decimal import unscaled_to_minimal_bytes

        bucket_99_95 = (mmh3.hash(unscaled_to_minimal_bytes(9995)) & 0x7FFFFFFF) % 8
        assert bucket_99_95 != 0
        extra_rows = {"g": [(Decimal("99.95"), 8)]}
        extra_path = _write_file(tmp, "g", extra_rows["g"])
        statistics = data_file_statistics_from_parquet_metadata(
            parquet_metadata=pq.read_metadata(extra_path),
            stats_columns=compute_statistics_plan(table.schema(), table.metadata.properties),
            parquet_column_mapping=parquet_path_to_id_mapping(table.schema()),
        )
        extra = DataFile(
            content=DataFileContent.DATA,
            file_path=extra_path,
            file_format=FileFormat.PARQUET,
            partition=Record(amount_trunc=Decimal("99.90"), amount_bucket=bucket_99_95),
            file_size_in_bytes=os.path.getsize(extra_path),
            sort_order_id=None,
            spec_id=table.metadata.default_spec_id,
            equality_ids=None,
            key_metadata=None,
            **statistics.to_serialized_dict(),
        )
        with table.transaction() as transaction:
            with transaction.update_snapshot().overwrite() as update:
                update.append_data_file(extra)
        for spelling in SPELLINGS_100:
            _assert_scan(table.scan(row_filter=EqualTo("amount", Decimal(spelling))), [1, 2], ["a"], 2)
