def _ids(scan):
    return sorted(scan.to_arrow().column("id").to_pylist())


def _planned_files(scan):
    return sorted(os.path.basename(task.file.file_path).removesuffix(".parquet") for task in scan.plan_files())


def _assert_scan(scan, expected_ids, expected_files, expected_count=None):
    """Check rows, batches, file eligibility, counts and idempotency."""
    assert _ids(scan) == expected_ids
    batch_ids = []
    for batch in scan.to_arrow_batch_reader():
        batch_ids.extend(batch.column("id").to_pylist())
    assert sorted(batch_ids) == expected_ids
    assert _planned_files(scan) == sorted(expected_files)
    # Repeated planning and reading must be idempotent.
    assert _ids(scan) == expected_ids
    assert _planned_files(scan) == sorted(expected_files)
    if expected_count is not None:
        assert scan.count() == expected_count
    return list(scan.plan_files())


ROWS_ALL = [1, 2, 3, 4, 5, 7]

TRUNCATE_FILES = [
    ["a"],  # EqualTo
    ["a", "b", "c", "d", "e", "f"],  # NotEqual: truncate has no inclusive projection
    ["b", "e", "f"],  # LessThan: partitions <= 99.90
    ["a", "b", "e", "f"],  # LessThanOrEqual: partitions <= 100.00
    ["d"],  # GreaterThan: partitions >= 100.00, then stats exclude a
    ["a", "d"],  # GreaterThanOrEqual: partitions >= 100.00
    ["a", "b"],  # In: truncations {100.00, 99.90}; stats exclude f
    ["a", "b", "c", "d", "e", "f"],  # NotIn: no inclusive projection
    ["a"],  # And: intersection of the two partition projections
    ["a", "e"],  # Or: union of the two partition projections
    ["a", "b", "c", "d", "e", "f"],  # NOT: rewritten to NotEqual
]
IDENTITY_FILES = [
    ["a"],
    ["b", "c", "d", "e", "f"],
    ["b", "e", "f"],
    ["a", "b", "e", "f"],
    ["d"],
    ["a", "d"],
    ["a", "b"],
    ["b", "c", "d", "e", "f"],
    ["a"],
    ["a", "e"],
    ["b", "c", "d", "e", "f"],
]
# Bucket has an inclusive projection only for equality and In, so comparisons
# fall back to file statistics (or the whole table when statistics are absent).
BUCKET_FILES = [
    ["a"],
    ["a", "b", "c", "d", "e", "f"],
    ["b", "e", "f"],
    ["a", "b", "e", "f"],
    ["d"],
    ["a", "d"],
    ["a", "b"],
    ["a", "b", "c", "d", "e", "f"],
    ["a"],
    ["a", "e"],
    ["a", "b", "c", "d", "e", "f"],
]

# Counts for the predicates whose residual is fully evaluated by the Arrow
# read path. NotEqual/NotIn/NOT are checked for spelling-invariance below
# instead, because a null-only file is planned and its record count is used
# when the residual evaluates to AlwaysTrue (pre-existing null/count rule).
EXACT_COUNTS = {0: 2, 2: 3, 3: 5, 4: 1, 5: 3, 6: 3, 8: 2, 9: 3}


def _cases_for(spelling):
    """Return (expression, expected ids, file list index) for a spelling."""
    cases = [
        (EqualTo("amount", spelling), [1, 2]),
        (NotEqualTo("amount", spelling), [3, 4, 5, 7]),
        (LessThan("amount", spelling), [3, 4, 5]),
        (LessThanOrEqual("amount", spelling), [1, 2, 3, 4, 5]),
        (GreaterThan("amount", spelling), [7]),
        (GreaterThanOrEqual("amount", spelling), [1, 2, 7]),
        (In("amount", [spelling, Decimal("99.99")]), [1, 2, 3]),
        (NotIn("amount", [spelling]), [3, 4, 5, 7]),
        (And(GreaterThan("amount", Decimal("99.99")), LessThanOrEqual("amount", spelling)), [1, 2]),
        (Or(EqualTo("amount", spelling), EqualTo("amount", Decimal("0.05"))), [1, 2, 5]),
        (Not(EqualTo("amount", spelling)), [3, 4, 5, 7]),
    ]
    return cases


@pytest.mark.parametrize("spelling", SPELLINGS_100)
@pytest.mark.parametrize(
    "spec_fixture, file_expectations",
    [
        ("truncate_table", TRUNCATE_FILES),
        ("identity_table", IDENTITY_FILES),
        ("bucket_table", BUCKET_FILES),
    ],
)
def test_spelling_does_not_change_rows_files_or_counts(spelling, spec_fixture, file_expectations, request):
    table = request.getfixturevalue(spec_fixture)
    for index, (expression, expected_ids) in enumerate(_cases_for(spelling)):
        scan = table.scan(row_filter=expression)
        _assert_scan(
            scan,
            expected_ids,
            file_expectations[index],
            expected_count=EXACT_COUNTS.get(index),
        )


def test_counts_are_spelling_invariant(truncate_table):
    table = truncate_table
    for index in range(len(_cases_for("100.00"))):
        counts = {table.scan(row_filter=_cases_for(spelling)[index][0]).count() for spelling in SPELLINGS_100}
        assert len(counts) == 1, (index, counts)


def test_far_away_partitions_are_pruned(truncate_table):
    table = truncate_table
    scan = table.scan(row_filter=EqualTo("amount", Decimal("5000.00")))
    assert list(scan.plan_files()) == []
    assert scan.count() == 0
    assert scan.to_arrow().num_rows == 0


def test_projection_without_amount_column(truncate_table):
    table = truncate_table
    scan = table.scan(row_filter=EqualTo("amount", Decimal("1E+2")), selected_fields=("id",))
    arrow = scan.to_arrow()
    assert arrow.column_names == ["id"]
    assert sorted(arrow.column("id").to_pylist()) == [1, 2]


def test_limit(truncate_table):
    table = truncate_table
    scan = table.scan(row_filter=EqualTo("amount", Decimal("100.000")), limit=1)
    assert scan.to_arrow().num_rows == 1


def test_null_column_semantics(truncate_table):
    table = truncate_table
    _assert_scan(table.scan(row_filter=EqualTo("amount", Decimal("1E+2"))), [1, 2], ["a"])
    _assert_scan(table.scan(row_filter=IsNull("amount")), [6], ["c"])
    _assert_scan(table.scan(row_filter=NotNull("amount")), ROWS_ALL, ["a", "b", "f", "e", "d"])
    # The null row never satisfies a decimal comparison.
    _assert_scan(table.scan(row_filter=GreaterThan("amount", Decimal("1E+2"))), [7], ["d"])


def test_bad_input_then_valid_input(truncate_table):
    table = truncate_table
    for bad in ["100.001", "NaN", "Infinity", "abc"]:
        with pytest.raises(ValueError):
            table.scan(row_filter=EqualTo("amount", bad)).plan_files()
    _assert_scan(table.scan(row_filter=EqualTo("amount", Decimal("100.00"))), [1, 2], ["a"], 2)


